use tauri_specta::{collect_commands, Builder};

pub fn generate_bindings() -> Builder<tauri::Wry> {
    // TAURI_CREATOR:SPECTA_MODULE_IMPORTS
    // TAURI_CREATOR:END_SPECTA_MODULE_IMPORTS

    Builder::<tauri::Wry>::new().commands(collect_commands![
        greet,
        // TAURI_CREATOR:SPECTA_COMMANDS
        // TAURI_CREATOR:END_SPECTA_COMMANDS
    ])
}

/// Export TypeScript bindings to the frontend.
/// Run with: cargo test export_bindings -- --ignored
#[allow(dead_code)]
pub fn export_ts_bindings() {
    let output = std::env::var_os("TAURI_CREATOR_BINDINGS_OUTPUT")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/tauri-bindings.ts"));
    if let Some(parent) = output.parent() {
        std::fs::create_dir_all(parent).expect("Failed to create bindings directory");
    }
    generate_bindings()
        .export(
            specta_typescript::Typescript::default()
                .header("// Auto-generated by tauri-specta. DO NOT EDIT.\n\n"),
            output,
        )
        .expect("Failed to export TypeScript bindings");
}

